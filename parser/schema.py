"""
Схема данных новости, которую парсер передаёт дальше (редактору/следующему шагу).

Обоснование набора полей и то, что сознательно исключено, — см. в переписке/доке по
архитектуре парсера (раздел "Схема данных на одну новость"). Коротко:
- Обязательные поля: title, text, source_url, source_name, published_at.
- image_url — НЕОБЯЗАТЕЛЬНОЕ поле (уточнение от 07.09.2026, отменяет более раннее решение
  от 03.09.2026, когда картинка была обязательной). Пользователь явно попросил не отбрасывать
  новости без картинки: если картинка нашлась — публикуем с ней, если нет — без неё. См.
  sources.py, _entry_to_news_item — там больше нет фильтрации по наличию картинки.
- internal_id — рекомендован, не обязателен по смыслу, но дёшев и полезен для трассировки.
- language — пока хардкодится на уровне источника (SourceConfig.language), т.к. отдельного
  языкового детектора в скелете нет — это открытый вопрос, важен только если в списке
  источников появятся не-RU сайты.
- Сознательно НЕ включены: полный HTML, категория/тег от парсера, дедуп-фингерпринт — эти
  поля либо не нужны получателю батча, либо являются суждением о релевантности, которое,
  по договорённости, не должен делать парсер.
"""

from dataclasses import dataclass, asdict
from typing import Optional


@dataclass
class NewsItem:
    internal_id: str          # стабильный id записи для трассировки, не для контента поста
    title: str
    text: str                 # очищенный текст/выжимка (HTML-теги убраны) — см. sources.py
    source_url: str
    source_name: str
    published_at: str         # ISO 8601, UTC, если дата не распозналась — пустая строка
    image_url: Optional[str] = None  # НЕОБЯЗАТЕЛЬНОЕ поле (с 07.09.2026) — если картинка
                               # нашлась, публикуем с ней, если нет — без неё (None)
    language: str = "ru"

    def to_dict(self) -> dict:
        return asdict(self)
